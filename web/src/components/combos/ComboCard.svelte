<script lang="ts">
  import {
    Check,
    Clock,
    Copy,
    Eye,
    Gavel,
    Layers,
    Loader2,
    Play,
    SlidersHorizontal,
    Sparkles,
    Wand2,
    X
  } from 'lucide-svelte'
  import type { Combo } from '../../api/client'
  import Card from '../../lib/ui/Card.svelte'
  import ComboActionsMenu from './ComboActionsMenu.svelte'
  import {
    BUDGET_CALLS_HELP,
    BUDGET_WINDOW_HELP,
    budgetWindowMsToMinutes,
    comboStrategyOptions,
    effectiveComboStrategy,
    getComboModels,
    hasReasoning,
    hasVision,
    INHERIT_STRATEGY,
    MAX_BUDGET_CALLS,
    MAX_BUDGET_WINDOW_MINUTES,
    MAX_FIRST_TOKEN_TIMEOUT_SECONDS,
    resolveComboStrategy,
    RESPONSE_TIMEOUT_HELP,
    secondsToTimeoutMs,
    timeoutMsToSeconds,
    isAutoGenerated,
    isAutoMember,
    smartPolicyLabel,
    smartRuleCount,
    type ComboStrategyInfo
  } from './types'

  interface Props {
    combo: Combo
    strategyInfo?: ComboStrategyInfo
    globalStrategy?: string | null
    copiedId?: string | null
    onSetStrategy: (combo: Combo, strategy: string) => void
    onSetResponseTimeout: (combo: Combo, timeoutMs: number) => void
    onToggleStoredOrder: (combo: Combo, respect: boolean) => void
    /** 0 clears the ceiling. */
    onSetBudgetCalls: (combo: Combo, budgetCalls: number) => void
    /** 0 clears the window so the backend default applies. */
    onSetBudgetWindow: (combo: Combo, windowMs: number) => void
    /** Sets the advertised context window mode: min | max | custom (null clears). */
    onSetContextWindowMode: (combo: Combo, mode: 'min' | 'max' | 'custom' | null) => void
    /** Sets (or clears with 0) the explicit advertised context window in custom mode. */
    onSetContextWindow: (combo: Combo, contextWindow: number) => void
    onOpenJudgePicker: (combo: Combo) => void
    onClearJudge: (comboName: string) => void
    onOpenRouterPicker: (combo: Combo) => void
    onOpenPolicyModal: (combo: Combo) => void
    onCopy: (name: string, id: string) => void
    onEdit: (combo: Combo) => void
    onDelete: (combo: Combo) => void
    onTest?: (combo: Combo) => void
    isTesting?: boolean
    testData?: {
      results?: Record<string, { ok: boolean; latencyMs: number; error?: string }>
      summary?: { total: number; alive: number; dead: number }
      activeModel?: string | null
    } | null
    isSelected?: boolean
    onToggleSelect?: (combo: Combo) => void
  }

  let {
    combo,
    strategyInfo = {},
    globalStrategy = null,
    copiedId = null,
    onSetStrategy,
    onSetResponseTimeout,
    onToggleStoredOrder,
    onSetBudgetCalls,
    onSetBudgetWindow,
    onSetContextWindowMode,
    onSetContextWindow,
    onOpenJudgePicker,
    onClearJudge,
    onOpenRouterPicker,
    onOpenPolicyModal,
    onCopy,
    onEdit,
    onDelete,
    onTest,
    isTesting = false,
    testData = null,
    isSelected = false,
    onToggleSelect,
  }: Props = $props()

  let expandedModels = $state(false)
  let tuningOpen = $state(false)

  let modelsList = $derived(getComboModels(combo))
  let visibleModels = $derived(expandedModels ? modelsList : modelsList.slice(0, 4))
  let ruleCount = $derived(smartRuleCount(combo))

  function handleToggleSelect(e: Event) {
    e.stopPropagation()
    onToggleSelect?.(combo)
  }

  function handleResponseTimeoutChange(e: Event) {
    const input = e.currentTarget as HTMLInputElement
    const timeoutMs = secondsToTimeoutMs(input.value)
    if (!input.reportValidity() || timeoutMs === null) return
    onSetResponseTimeout(combo, timeoutMs)
  }

  function handleBudgetCallsChange(e: Event) {
    const input = e.currentTarget as HTMLInputElement
    if (!input.reportValidity()) return
    const raw = input.value.trim()
    if (raw === '') {
      onSetBudgetCalls(combo, 0)
      return
    }
    const calls = Number(raw)
    if (!Number.isSafeInteger(calls) || calls < 0 || calls > MAX_BUDGET_CALLS) return
    onSetBudgetCalls(combo, calls)
  }

  let budgetWindowMinutes = $derived(budgetWindowMsToMinutes(strategyInfo.budgetWindowMs))

  function handleBudgetWindowChange(e: Event) {
    const input = e.currentTarget as HTMLInputElement
    if (!input.reportValidity()) return
    const raw = input.value.trim()
    if (raw === '') {
      onSetBudgetWindow(combo, 0)
      return
    }
    const minutes = Number(raw)
    if (!Number.isSafeInteger(minutes) || minutes < 1 || minutes > MAX_BUDGET_WINDOW_MINUTES) return
    onSetBudgetWindow(combo, minutes * 60000)
  }

  function handleContextWindowChange(e: Event) {
    const input = e.currentTarget as HTMLInputElement
    if (!input.reportValidity()) return
    const raw = input.value.trim()
    if (raw === '') {
      onSetContextWindow(combo, 0)
      return
    }
    const tokens = Number(raw)
    if (!Number.isSafeInteger(tokens) || tokens < 0) return
    onSetContextWindow(combo, tokens)
  }

  let isAutoGeneratedCombo = $derived(isAutoGenerated(combo))
  let currentStrategy = $derived(
    strategyInfo.fallbackStrategy ? resolveComboStrategy(strategyInfo.fallbackStrategy) : INHERIT_STRATEGY
  )
  let timeoutSeconds = $derived(timeoutMsToSeconds(strategyInfo.firstTokenTimeoutMs))
  let judgeModel = $derived(strategyInfo.judgeModel || '')
  let isFusion = $derived(effectiveComboStrategy(strategyInfo.fallbackStrategy, globalStrategy) === 'fusion')
  let isSmart = $derived(effectiveComboStrategy(strategyInfo.fallbackStrategy, globalStrategy) === 'smart')
  let isCascade = $derived(effectiveComboStrategy(strategyInfo.fallbackStrategy, globalStrategy) === 'cascade')
  let routerModel = $derived(strategyInfo.routerModel || '')
  let policyLabel = $derived(smartPolicyLabel(strategyInfo))
  let strategyOptions = $derived(comboStrategyOptions(globalStrategy))

  let hasCustomTuning = $derived(
    Boolean(
      (strategyInfo.firstTokenTimeoutMs ?? 0) > 0 ||
      (strategyInfo.budgetCalls ?? 0) > 0 ||
      strategyInfo.respectStoredOrder === true ||
      (strategyInfo.contextWindowMode && strategyInfo.contextWindowMode !== 'min')
    )
  )

  const isCopied = $derived(copiedId === combo.id)
</script>

<Card padding="sm" class="group transition-all duration-150 hover:border-border-subtle/80">
  <div class="flex flex-col gap-3 min-w-0">
    <!-- Header row: Select checkbox, Icon, Title, Badges, and Top Actions -->
    <div class="flex items-start justify-between gap-2 min-w-0">
      <div class="flex items-center gap-2.5 min-w-0 flex-1">
        <input
          type="checkbox"
          checked={isSelected}
          onchange={handleToggleSelect}
          class="size-4.5 rounded cursor-pointer accent-brand-500 shrink-0"
          title="Select for bulk actions"
        />
        <div class="size-8 rounded-lg bg-brand-500/10 text-brand-500 flex items-center justify-center shrink-0">
          <Layers class="w-4 h-4" />
        </div>
        <div class="flex items-center gap-1.5 min-w-0">
          <code class="font-mono text-sm sm:text-base font-semibold text-text-main truncate">{combo.name}</code>
          <button
            type="button"
            onclick={() => onCopy(combo.name, combo.id)}
            class="p-1 rounded text-text-muted hover:text-brand-500 transition-colors shrink-0 cursor-pointer"
            title={isCopied ? 'Copied to clipboard' : 'Copy combo name'}
          >
            {#if isCopied}
              <Check class="w-3.5 h-3.5 text-emerald-500" />
            {:else}
              <Copy class="w-3.5 h-3.5" />
            {/if}
          </button>
        </div>

        <!-- Badges on desktop -->
        <div class="hidden sm:flex items-center gap-1.5 shrink-0">
          {#if isAutoGeneratedCombo}
            <span class="inline-flex items-center gap-1 rounded-full bg-surface-3 px-2 py-0.5 text-[10px] font-medium text-text-muted border border-border">
              <Wand2 class="w-2.5 h-2.5" />
              Auto-generated
            </span>
          {/if}
          {#if ruleCount > 0}
            <span
              class="inline-flex items-center gap-1 rounded-full bg-brand-500/10 px-2 py-0.5 text-[10px] font-medium text-brand-500 border border-brand-500/30"
              title="{ruleCount} smart rule{ruleCount === 1 ? '' : 's'} keep this combo in step with the catalog"
            >
              <Wand2 class="w-2.5 h-2.5" />
              {ruleCount} smart rule{ruleCount === 1 ? '' : 's'}
            </span>
          {/if}
        </div>
      </div>

      <!-- Right Header: Test status & Quick Action Menu -->
      <div class="flex items-center gap-1.5 shrink-0">
        {#if testData?.summary}
          <span class="inline-flex items-center px-2 py-0.5 rounded text-[11px] font-medium {testData.summary.dead > 0 ? 'bg-rose-500/10 text-rose-600 dark:text-rose-400 border border-rose-500/30' : 'bg-emerald-500/10 text-emerald-700 dark:text-emerald-400 border border-emerald-500/30'}">
            {testData.summary.alive}/{testData.summary.total} Alive
          </span>
        {/if}
        {#if onTest && modelsList.length > 0}
          <button
            type="button"
            onclick={() => onTest(combo)}
            disabled={isTesting}
            class="hidden sm:inline-flex items-center gap-1 h-8 px-2 rounded-lg border border-border/70 hover:bg-surface-2 text-xs text-text-muted hover:text-text-main transition-colors cursor-pointer disabled:opacity-50"
            title="Test all models in this combo"
          >
            {#if isTesting}
              <Loader2 class="animate-spin text-brand-500 size-3.5" />
            {:else}
              <Play class="w-3.5 h-3.5 text-brand-500" />
            {/if}
            <span>Test</span>
          </button>
        {/if}
        <ComboActionsMenu
          {combo}
          {copiedId}
          {isTesting}
          hasModels={modelsList.length > 0}
          {onTest}
          {onCopy}
          {onEdit}
          {onDelete}
        />
      </div>
    </div>

    <!-- Mobile-only Badges row -->
    <div class="flex sm:hidden flex-wrap items-center gap-1.5 -mt-1">
      {#if isAutoGeneratedCombo}
        <span class="inline-flex items-center gap-1 rounded-full bg-surface-3 px-2 py-0.5 text-[10px] font-medium text-text-muted border border-border">
          <Wand2 class="w-2.5 h-2.5" />
          Auto-generated
        </span>
      {/if}
      {#if ruleCount > 0}
        <span class="inline-flex items-center gap-1 rounded-full bg-brand-500/10 px-2 py-0.5 text-[10px] font-medium text-brand-500 border border-brand-500/30">
          <Wand2 class="w-2.5 h-2.5" />
          {ruleCount} rule{ruleCount === 1 ? '' : 's'}
        </span>
      {/if}
    </div>

    <!-- Models pill container -->
    <div class="flex flex-wrap items-center gap-1.5 min-w-0">
      {#if modelsList.length === 0}
        <span class="text-xs text-text-muted italic">No models configured</span>
      {:else}
        {#each visibleModels as model}
          {@const res = testData?.results?.[model]}
          {@const isModelActive = isTesting && (testData?.activeModel ? testData.activeModel === model : !res)}
          <div
            class="inline-flex items-center gap-1 rounded-md border px-2 py-1 font-mono text-xs transition-colors {res ? (res.ok ? 'border-emerald-500/40 bg-emerald-500/10 text-emerald-700 dark:text-emerald-400 font-medium' : 'border-rose-500/40 bg-rose-500/10 text-rose-700 dark:text-rose-400 font-medium') : 'border-border/60 bg-surface-2 text-text-main'}"
            title={res ? (res.ok ? `Alive · ${res.latencyMs}ms` : `Dead · ${res.error || 'Failed'}`) : isModelActive ? 'Testing...' : undefined}
          >
            {#if isModelActive}
              <Loader2 class="animate-spin text-brand-500 size-3 shrink-0" />
            {:else if res}
              <span class="material-symbols-outlined text-[13px] {res.ok ? 'text-emerald-600 dark:text-emerald-400' : 'text-rose-600 dark:text-rose-400'}">
                {res.ok ? 'check_circle' : 'cancel'}
              </span>
            {/if}
            <span class="truncate max-w-[170px] sm:max-w-[240px]">{model}</span>
            {#if res?.ok}
              <span class="text-[10px] opacity-75 font-sans font-normal ml-0.5">{res.latencyMs}ms</span>
            {/if}
            {#if isAutoMember(combo, model)}
              <span class="text-[9px] uppercase tracking-wide text-brand-500 font-semibold ml-0.5" title="Added by a smart rule">auto</span>
            {/if}
            {#if hasVision(model)}
              <Eye class="w-3 h-3 text-blue-500 shrink-0 ml-0.5" role="img" aria-label="Vision support" />
            {/if}
            {#if hasReasoning(model)}
              <Sparkles class="w-3 h-3 text-amber-500 shrink-0 ml-0.5" role="img" aria-label="Reasoning support" />
            {/if}
          </div>
        {/each}

        {#if modelsList.length > 4}
          <button
            type="button"
            onclick={(e) => {
              e.stopPropagation()
              expandedModels = !expandedModels
            }}
            class="text-xs font-medium text-brand-500 hover:underline px-1 py-0.5 rounded cursor-pointer"
          >
            {expandedModels ? 'Show less' : `+${modelsList.length - 4} more`}
          </button>
        {/if}
      {/if}
    </div>

    <!-- Fusion / Smart Router helpers -->
    {#if isFusion}
      <div class="flex flex-wrap items-center gap-2 pt-1 border-t border-border/30">
        <span class="text-xs font-medium text-text-muted flex items-center gap-1">
          <Gavel class="w-3 h-3 text-purple-500" />
          Fusion Judge:
        </span>
        <button
          type="button"
          onclick={() => onOpenJudgePicker(combo)}
          class="inline-flex items-center gap-1 rounded-md border border-dashed border-brand-500/40 px-2 py-0.5 font-mono text-xs text-brand-500 hover:border-brand-500 hover:bg-brand-500/5 transition-colors cursor-pointer"
          title="Pick the model that fuses panel answers"
        >
          <span class="truncate max-w-[200px]">{judgeModel || `Auto (${modelsList[0] || 'first model'})`}</span>
        </button>
        {#if judgeModel}
          <button
            type="button"
            onclick={() => onClearJudge(combo.name)}
            class="p-0.5 rounded text-text-muted hover:text-rose-500 hover:bg-rose-500/10 transition-colors cursor-pointer"
            title="Reset judge to Auto"
          >
            <X class="w-3 h-3" />
          </button>
        {/if}
      </div>
    {/if}

    {#if isSmart}
      <div class="flex flex-wrap items-center gap-2 pt-1 border-t border-border/30">
        <span class="text-xs font-medium text-text-muted flex items-center gap-1">
          <span class="material-symbols-outlined text-[13px] text-blue-500">psychology</span>
          Smart Router:
        </span>
        <button
          type="button"
          onclick={() => onOpenRouterPicker(combo)}
          class="inline-flex items-center gap-1 rounded-md border border-dashed border-brand-500/40 px-2 py-0.5 font-mono text-xs text-brand-500 hover:border-brand-500 hover:bg-brand-500/5 transition-colors cursor-pointer"
        >
          <span class="truncate max-w-[180px]">{routerModel || 'Auto (oc/jev-1.13-free)'}</span>
        </button>
        <button
          type="button"
          onclick={() => onOpenPolicyModal(combo)}
          class="inline-flex items-center gap-1 rounded-md border border-border bg-surface-2 px-2 py-0.5 text-xs text-text-main hover:border-brand-500/50 hover:bg-brand-500/5 transition-colors cursor-pointer"
        >
          <span class="material-symbols-outlined text-[13px] text-text-muted">tune</span>
          <span class="font-medium">{policyLabel}</span>
        </button>
      </div>
    {/if}

    <!-- Bottom Controls: Strategy selection & Tuning toggle -->
    <div class="flex flex-col sm:flex-row sm:items-center justify-between gap-2 pt-2 border-t border-border/40">
      <div class="flex flex-wrap items-center gap-2 flex-1 min-w-0">
        <div class="w-full sm:w-[210px] shrink-0">
          <select
            value={currentStrategy}
            onchange={(e) => onSetStrategy(combo, e.currentTarget.value)}
            class="w-full bg-surface-2 border border-border rounded-lg px-2.5 py-1.5 text-xs font-medium text-text-main focus:outline-none focus:border-brand-500 cursor-pointer"
          >
            {#each strategyOptions as strategy (strategy.value)}
              <option value={strategy.value}>{strategy.label}</option>
            {/each}
          </select>
        </div>

        <button
          type="button"
          onclick={() => (tuningOpen = !tuningOpen)}
          class="inline-flex items-center gap-1.5 h-8 px-2.5 rounded-lg border text-xs font-medium transition-colors cursor-pointer {tuningOpen || hasCustomTuning ? 'bg-brand-500/10 border-brand-500/40 text-brand-500' : 'border-border/70 text-text-muted hover:text-text-main hover:bg-surface-2'}"
          title="Toggle advanced tuning (Timeout, Budget, Context Window, Order)"
        >
          <SlidersHorizontal class="w-3.5 h-3.5" />
          <span>Tuning</span>
          {#if hasCustomTuning}
            <span class="size-1.5 rounded-full bg-brand-500 shrink-0"></span>
          {/if}
        </button>

        <!-- Summary indicators if tuning is active -->
        {#if !tuningOpen && hasCustomTuning}
          <div class="hidden md:flex items-center gap-1.5 text-[11px] text-text-muted">
            {#if (strategyInfo.firstTokenTimeoutMs ?? 0) > 0}
              <span class="inline-flex items-center gap-0.5 px-1.5 py-0.5 rounded bg-surface-2 border border-border/50">
                <Clock class="w-2.5 h-2.5 text-amber-500" />
                {timeoutSeconds}s
              </span>
            {/if}
            {#if (strategyInfo.budgetCalls ?? 0) > 0}
              <span class="inline-flex items-center gap-0.5 px-1.5 py-0.5 rounded bg-surface-2 border border-border/50">
                {strategyInfo.budgetCalls} calls
              </span>
            {/if}
            {#if strategyInfo.respectStoredOrder}
              <span class="px-1.5 py-0.5 rounded bg-surface-2 border border-border/50">
                Fixed order
              </span>
            {/if}
          </div>
        {/if}
      </div>

      <!-- Mobile quick test button -->
      {#if onTest && modelsList.length > 0}
        <button
          type="button"
          onclick={() => onTest(combo)}
          disabled={isTesting}
          class="flex sm:hidden items-center justify-center gap-1.5 h-8 w-full rounded-lg border border-border/70 bg-surface-2 text-xs font-medium text-text-main cursor-pointer disabled:opacity-50"
        >
          {#if isTesting}
            <Loader2 class="animate-spin text-brand-500 size-3.5 shrink-0" />
          {:else}
            <Play class="w-3.5 h-3.5 text-brand-500" />
          {/if}
          <span>{isTesting ? 'Testing Models...' : 'Test Combo'}</span>
        </button>
      {/if}
    </div>

    <!-- Collapsible Advanced Tuning Panel -->
    {#if tuningOpen}
      <div class="mt-1 pt-3 border-t border-border/50 bg-surface-2/40 rounded-lg p-3 grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-4 gap-3 text-xs">
        <!-- 1. Respect Stored Order -->
        {#if !isSmart && !isCascade}
          <div class="flex flex-col gap-1">
            <span class="font-medium text-text-main">Model Order</span>
            <label
              class="flex items-center gap-2 cursor-pointer mt-1 select-none text-text-muted hover:text-text-main"
              title="Skip the rotation strategy and try models in the order shown."
            >
              <input
                type="checkbox"
                checked={strategyInfo.respectStoredOrder === true}
                onchange={(e) => onToggleStoredOrder(combo, e.currentTarget.checked)}
                class="size-4 rounded cursor-pointer accent-brand-500"
              />
              <span>Respect stored order</span>
            </label>
          </div>
        {/if}

        <!-- 2. Response Timeout -->
        <div class="flex flex-col gap-1">
          <label for="response-timeout-{combo.id}" class="font-medium text-text-main flex items-center gap-1" title={RESPONSE_TIMEOUT_HELP}>
            <Clock class="w-3.5 h-3.5 text-brand-500" />
            Response timeout
          </label>
          <div class="flex items-center gap-1.5 mt-0.5">
            <input
              id="response-timeout-{combo.id}"
              type="number"
              min="0"
              max={MAX_FIRST_TOKEN_TIMEOUT_SECONDS}
              step="any"
              placeholder="Off"
              value={timeoutSeconds || ''}
              onchange={handleResponseTimeoutChange}
              class="w-full min-h-[34px] rounded-md border border-border bg-surface px-2.5 py-1 text-xs text-text-main focus:outline-none focus:border-brand-500"
            />
            <span class="text-text-muted shrink-0">sec</span>
          </div>
        </div>

        <!-- 3. Call Budget & Window -->
        <div class="flex flex-col gap-1">
          <label for="call-budget-{combo.id}" class="font-medium text-text-main" title={BUDGET_CALLS_HELP}>
            Call budget
          </label>
          <div class="flex items-center gap-1.5 mt-0.5">
            <input
              id="call-budget-{combo.id}"
              type="number"
              min="0"
              max={MAX_BUDGET_CALLS}
              step="1"
              placeholder="Unlimited"
              value={strategyInfo.budgetCalls || ''}
              onchange={handleBudgetCallsChange}
              class="w-full min-h-[34px] rounded-md border border-border bg-surface px-2.5 py-1 text-xs text-text-main focus:outline-none focus:border-brand-500"
            />
            <span class="text-text-muted shrink-0">calls</span>
          </div>
        </div>

        <!-- 4. Budget Window (shown if budget set) or Context Window Mode -->
        {#if strategyInfo.budgetCalls}
          <div class="flex flex-col gap-1">
            <label for="budget-window-{combo.id}" class="font-medium text-text-main" title={BUDGET_WINDOW_HELP}>
              Budget window
            </label>
            <div class="flex items-center gap-1.5 mt-0.5">
              <input
                id="budget-window-{combo.id}"
                type="number"
                min="1"
                max={MAX_BUDGET_WINDOW_MINUTES}
                step="1"
                placeholder="60"
                value={budgetWindowMinutes}
                onchange={handleBudgetWindowChange}
                class="w-full min-h-[34px] rounded-md border border-border bg-surface px-2.5 py-1 text-xs text-text-main focus:outline-none focus:border-brand-500"
              />
              <span class="text-text-muted shrink-0">min</span>
            </div>
          </div>
        {/if}

        <!-- 5. Context Window Mode -->
        <div class="flex flex-col gap-1">
          <label for="window-mode-{combo.id}" class="font-medium text-text-main">
            Context window mode
          </label>
          <div class="flex items-center gap-1.5 mt-0.5">
            <select
              id="window-mode-{combo.id}"
              value={strategyInfo.contextWindowMode || 'min'}
              onchange={(e) => onSetContextWindowMode(combo, e.currentTarget.value as 'min' | 'max' | 'custom')}
              class="w-full min-h-[34px] rounded-md border border-border bg-surface px-2 py-1 text-xs text-text-main focus:outline-none focus:border-brand-500 cursor-pointer"
            >
              <option value="min">min (safest)</option>
              <option value="max">max (widest)</option>
              <option value="custom">custom tokens</option>
            </select>
            {#if strategyInfo.contextWindowMode === 'custom'}
              <input
                type="number"
                min="0"
                step="1"
                placeholder="Tokens"
                value={strategyInfo.contextWindow || ''}
                onchange={handleContextWindowChange}
                class="w-24 min-h-[34px] rounded-md border border-border bg-surface px-2 py-1 text-xs text-text-main focus:outline-none focus:border-brand-500"
              />
            {/if}
          </div>
        </div>
      </div>
    {/if}
  </div>
</Card>
